-- ==============================================================================
-- ModelConnector Platform Enterprise DDL Schema: RBAC & Dynamic Menus
-- Tables: COMPANIES, ROLES, PERMISSIONS, ROLE_PERMISSIONS, USERS, MENUS, ROLE_MENUS, COMPANY_MENUS
-- Conforms to:
-- - Invariant: Avoid generic ID; use meaningful column names
-- - Invariant: All Table and Column names must be strictly UPPER CASE
-- ==============================================================================

-- 1. Multi-Tenant Enterprise Companies Table
CREATE TABLE IF NOT EXISTS COMPANIES (
    COMPANY_ID VARCHAR(64) PRIMARY KEY,
    COMPANY_NAME VARCHAR(128) NOT NULL,
    COMPANY_DOMAIN VARCHAR(128) NOT NULL UNIQUE,
    SUBSCRIPTION_TIER VARCHAR(32) NOT NULL DEFAULT 'ENTERPRISE',
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_COMPANIES_DOMAIN ON COMPANIES(COMPANY_DOMAIN);

-- 2. Role Definitions Table
CREATE TABLE IF NOT EXISTS ROLES (
    ROLE_ID VARCHAR(64) PRIMARY KEY,
    ROLE_NAME VARCHAR(64) NOT NULL UNIQUE,
    ROLE_DESCRIPTION TEXT NOT NULL,
    IS_SYSTEM_ROLE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Granular Action Permissions Table
CREATE TABLE IF NOT EXISTS PERMISSIONS (
    PERMISSION_ID VARCHAR(64) PRIMARY KEY,
    PERMISSION_CODE VARCHAR(64) NOT NULL UNIQUE,
    RESOURCE_NAME VARCHAR(64) NOT NULL,
    ACTION_NAME VARCHAR(32) NOT NULL,
    DESCRIPTION_TEXT TEXT NOT NULL,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Role-Permission Cross-Reference Table
CREATE TABLE IF NOT EXISTS ROLE_PERMISSIONS (
    ROLE_ID VARCHAR(64) NOT NULL,
    PERMISSION_ID VARCHAR(64) NOT NULL,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERM_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ROLE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROLE_PERM_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS(PERMISSION_ID) ON DELETE CASCADE
);

-- 5. Enterprise Users & Credentials Table
CREATE TABLE IF NOT EXISTS USERS (
    USER_ID VARCHAR(64) PRIMARY KEY,
    COMPANY_ID VARCHAR(64) NOT NULL,
    ROLE_ID VARCHAR(64) NOT NULL,
    FULL_NAME VARCHAR(128) NOT NULL,
    USER_EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    AVATAR_URL TEXT,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_USERS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES(COMPANY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_USERS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ROLE_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_USERS_EMAIL ON USERS(USER_EMAIL);
CREATE INDEX IF NOT EXISTS IDX_USERS_COMPANY ON USERS(COMPANY_ID);
CREATE INDEX IF NOT EXISTS IDX_USERS_ROLE ON USERS(ROLE_ID);

-- 6. Dynamic Navigation Menus Table
CREATE TABLE IF NOT EXISTS MENUS (
    MENU_ID VARCHAR(64) PRIMARY KEY,
    MENU_LABEL VARCHAR(64) NOT NULL,
    MENU_ICON VARCHAR(32) NOT NULL,
    ROUTE_PATH VARCHAR(64) NOT NULL UNIQUE,
    BADGE_COUNT_KEY VARCHAR(32),
    SORT_ORDER INTEGER NOT NULL DEFAULT 0,
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    REQUIRED_PERMISSION VARCHAR(64),
    DESCRIPTION_TEXT TEXT,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_MENUS_SORT ON MENUS(SORT_ORDER ASC);

-- 7. Role-Menu Access Matrix Table
CREATE TABLE IF NOT EXISTS ROLE_MENUS (
    ROLE_ID VARCHAR(64) NOT NULL,
    MENU_ID VARCHAR(64) NOT NULL,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ROLE_ID, MENU_ID),
    CONSTRAINT FK_ROLE_MENUS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ROLE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROLE_MENUS_MENU FOREIGN KEY (MENU_ID) REFERENCES MENUS(MENU_ID) ON DELETE CASCADE
);

-- 8. Company-Level Menu Overrides & Enablement Table
CREATE TABLE IF NOT EXISTS COMPANY_MENUS (
    COMPANY_ID VARCHAR(64) NOT NULL,
    MENU_ID VARCHAR(64) NOT NULL,
    IS_ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (COMPANY_ID, MENU_ID),
    CONSTRAINT FK_COMPANY_MENUS_COMP FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES(COMPANY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMPANY_MENUS_MENU FOREIGN KEY (MENU_ID) REFERENCES MENUS(MENU_ID) ON DELETE CASCADE
);
