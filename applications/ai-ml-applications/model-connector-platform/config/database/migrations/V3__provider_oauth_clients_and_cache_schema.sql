-- Flyway Migration V3: Multi-Client OAuth Credentials & Distributed Model Cache DDL
-- Conforms to:
-- - Invariant: Zero generic ID; meaningful UPPER CASE column names
-- - Invariant: Zero DML / Zero Dummy Data — Pure Flyway DDL only
-- - Supports multiple Client IDs and Client Secrets per provider/model in DB
-- - Supports 24-hour distributed model discovery caching across all providers
-- ==============================================================================

-- 1. Multi-Client OAuth Configuration Table Per Provider & Model
CREATE TABLE IF NOT EXISTS PROVIDER_OAUTH_CLIENTS (
    OAUTH_CLIENT_CONFIG_ID VARCHAR(64) PRIMARY KEY,
    PROVIDER_ID VARCHAR(64) NOT NULL,
    MODEL_ID VARCHAR(64) NOT NULL DEFAULT '*',
    CLIENT_ALIAS VARCHAR(128) NOT NULL,
    CLIENT_ID VARCHAR(255) NOT NULL,
    CLIENT_SECRET TEXT NOT NULL,
    REDIRECT_URI VARCHAR(512),
    SCOPES_TEXT TEXT,
    TENANT_ID VARCHAR(128),
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_OAUTH_CLIENTS_PROVIDER ON PROVIDER_OAUTH_CLIENTS(PROVIDER_ID, IS_ACTIVE);
CREATE INDEX IF NOT EXISTS IDX_OAUTH_CLIENTS_MODEL ON PROVIDER_OAUTH_CLIENTS(PROVIDER_ID, MODEL_ID, IS_ACTIVE);

-- 2. Distributed Provider & Application Available Model Cache Table (24-Hour TTL)
CREATE TABLE IF NOT EXISTS PROVIDER_MODEL_CACHE (
    CACHE_KEY VARCHAR(128) PRIMARY KEY,
    PROVIDER_ID VARCHAR(64) NOT NULL,
    MODELS_JSON TEXT NOT NULL,
    FAMILY_KEYWORDS_JSON TEXT NOT NULL,
    CACHED_AT_MS BIGINT NOT NULL,
    EXPIRES_AT_MS BIGINT NOT NULL,
    TTL_MS BIGINT NOT NULL DEFAULT 86400000,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_MODEL_CACHE_PROVIDER ON PROVIDER_MODEL_CACHE(PROVIDER_ID);
