CREATE TABLE IF NOT EXISTS CLI_OAUTH_SESSIONS (
  SESSION_ID TEXT PRIMARY KEY,
  PROVIDER TEXT NOT NULL,
  MODEL_ID TEXT NOT NULL,
  AUTH_MODE TEXT NOT NULL,
  OAUTH_URL TEXT NOT NULL,
  CLIENT_ID TEXT,
  STATE TEXT,
  CODE_CHALLENGE TEXT,
  REDIRECT_URI TEXT,
  CLI_REDIRECT_URI TEXT,
  APP_REDIRECT_URI TEXT,
  AUTH_CODE TEXT,
  STATUS TEXT NOT NULL DEFAULT 'PENDING',
  ERROR_MESSAGE TEXT,
  ERROR_CODE TEXT,
  COMMIT_ID TEXT,
  USER_EMAIL TEXT,
  CREATED_AT TEXT NOT NULL,
  UPDATED_AT TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CLI_OAUTH_SESSIONS_STATUS ON CLI_OAUTH_SESSIONS(STATUS);
CREATE INDEX IF NOT EXISTS IDX_CLI_OAUTH_SESSIONS_STATE ON CLI_OAUTH_SESSIONS(STATE);
CREATE INDEX IF NOT EXISTS IDX_CLI_OAUTH_SESSIONS_MODEL ON CLI_OAUTH_SESSIONS(MODEL_ID);
