-- ==============================================================================
-- ModelConnector Platform Enterprise DDL Schema
-- Conforms to:
-- - Invariant: Avoid generic ID; use meaningful column names (MODEL_ID, SESSION_ID, etc.)
-- - Invariant: All Table and Column names must be strictly UPPER CASE
-- - Invariant: Multi-Dialect Support (PostgreSQL, MySQL, Oracle, SQL Server, SQLite)
-- ==============================================================================

-- 1. AI Models Catalog Table
CREATE TABLE IF NOT EXISTS MODELS (
    MODEL_ID VARCHAR(64) PRIMARY KEY,
    MODEL_NAME VARCHAR(128) NOT NULL,
    MODEL_FAMILY VARCHAR(32) NOT NULL,
    PROVIDER_NAME VARCHAR(64) NOT NULL,
    CONTEXT_WINDOW_SIZE INTEGER NOT NULL DEFAULT 128000,
    SUPPORTED_STRATEGIES VARCHAR(128) NOT NULL,
    LIFECYCLE_STATUS VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    DESCRIPTION_TEXT TEXT,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_MODELS_FAMILY ON MODELS(MODEL_FAMILY);
CREATE INDEX IF NOT EXISTS IDX_MODELS_STATUS ON MODELS(LIFECYCLE_STATUS);

-- 2. Multi-Turn Conversation Sessions Table
CREATE TABLE IF NOT EXISTS SESSIONS (
    SESSION_ID VARCHAR(64) PRIMARY KEY,
    SESSION_TITLE VARCHAR(255) NOT NULL,
    ACTIVE_MODEL_ID VARCHAR(64) NOT NULL,
    STRATEGY_MODE VARCHAR(32) NOT NULL DEFAULT 'api',
    TURN_COUNT INTEGER NOT NULL DEFAULT 0,
    SESSION_METADATA_JSON TEXT,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SESSIONS_MODEL FOREIGN KEY (ACTIVE_MODEL_ID) REFERENCES MODELS(MODEL_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_SESSIONS_UPDATED ON SESSIONS(UPDATED_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_SESSIONS_MODEL ON SESSIONS(ACTIVE_MODEL_ID);

-- 3. Conversation Messages Table
CREATE TABLE IF NOT EXISTS MESSAGES (
    MESSAGE_ID VARCHAR(64) PRIMARY KEY,
    SESSION_ID VARCHAR(64) NOT NULL,
    MESSAGE_ROLE VARCHAR(32) NOT NULL,
    MESSAGE_CONTENT TEXT NOT NULL,
    STRATEGY_MODE VARCHAR(32) NOT NULL,
    TOKEN_COUNT INTEGER NOT NULL DEFAULT 0,
    LATENCY_MS INTEGER NOT NULL DEFAULT 0,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_MESSAGES_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SESSIONS(SESSION_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_MESSAGES_SESSION ON MESSAGES(SESSION_ID);
CREATE INDEX IF NOT EXISTS IDX_MESSAGES_CREATED ON MESSAGES(CREATED_TIMESTAMP ASC);

-- 4. Context Attachment Items Table (Migrated from gemini-model-connector)
CREATE TABLE IF NOT EXISTS CONTEXT_ITEMS (
    CONTEXT_ID VARCHAR(64) PRIMARY KEY,
    SESSION_ID VARCHAR(64) NOT NULL,
    CONTEXT_TYPE VARCHAR(32) NOT NULL,
    CONTEXT_NAME VARCHAR(128) NOT NULL,
    CONTEXT_CONTENT TEXT NOT NULL,
    TOKEN_COUNT INTEGER NOT NULL DEFAULT 0,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CONTEXT_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SESSIONS(SESSION_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_CONTEXT_SESSION ON CONTEXT_ITEMS(SESSION_ID);

-- 5. Enterprise Audit Logs Table (Zero PII Governance & Distributed Tracing)
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
    AUDIT_LOG_ID VARCHAR(64) PRIMARY KEY,
    CORRELATION_ID VARCHAR(64) NOT NULL,
    TRACE_ID VARCHAR(64),
    SPAN_ID VARCHAR(32),
    MODEL_ID VARCHAR(64) NOT NULL,
    ACTION_NAME VARCHAR(64) NOT NULL,
    STRATEGY_MODE VARCHAR(32) NOT NULL,
    LATENCY_MS INTEGER NOT NULL,
    EXECUTION_STATUS VARCHAR(32) NOT NULL,
    CLIENT_IP VARCHAR(64),
    ERROR_MESSAGE TEXT,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_AUDIT_CORRELATION ON AUDIT_LOGS(CORRELATION_ID);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_TRACE ON AUDIT_LOGS(TRACE_ID);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_CREATED ON AUDIT_LOGS(CREATED_TIMESTAMP DESC);

-- 6. Model Provider Credentials Table (Salted Hashes Only, Zero Plaintext Secrets)
CREATE TABLE IF NOT EXISTS MODEL_CREDENTIALS (
    CREDENTIAL_ID VARCHAR(64) PRIMARY KEY,
    MODEL_FAMILY VARCHAR(32) NOT NULL,
    KEY_NAME VARCHAR(128) NOT NULL,
    KEY_HASH VARCHAR(128) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS IDX_CREDENTIALS_FAMILY_KEY ON MODEL_CREDENTIALS(MODEL_FAMILY, KEY_NAME);

-- 7. Multi-Client OAuth Configuration Table Per Provider & Model (Zero Hardcoded Secrets in YAML)
CREATE TABLE IF NOT EXISTS PROVIDER_OAUTH_CLIENTS (
    OAUTH_CLIENT_CONFIG_ID VARCHAR(64) PRIMARY KEY,
    PROVIDER_ID VARCHAR(64) NOT NULL,
    MODEL_ID VARCHAR(64) NOT NULL DEFAULT '*',
    CLIENT_ALIAS VARCHAR(128) NOT NULL,
    CLIENT_ID VARCHAR(255) NOT NULL,
    CLIENT_SECRET TEXT NOT NULL,
    REDIRECT_URI VARCHAR(512),
    SCOPES_TEXT TEXT,
    TENANT_ID VARCHAR(128),
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_OAUTH_CLIENTS_PROVIDER ON PROVIDER_OAUTH_CLIENTS(PROVIDER_ID, IS_ACTIVE);
CREATE INDEX IF NOT EXISTS IDX_OAUTH_CLIENTS_MODEL ON PROVIDER_OAUTH_CLIENTS(PROVIDER_ID, MODEL_ID, IS_ACTIVE);

-- 8. Distributed Provider & Application Available Model Cache Table (24-Hour TTL)
CREATE TABLE IF NOT EXISTS PROVIDER_MODEL_CACHE (
    CACHE_KEY VARCHAR(128) PRIMARY KEY,
    PROVIDER_ID VARCHAR(64) NOT NULL,
    MODELS_JSON TEXT NOT NULL,
    FAMILY_KEYWORDS_JSON TEXT NOT NULL,
    CACHED_AT_MS BIGINT NOT NULL,
    EXPIRES_AT_MS BIGINT NOT NULL,
    TTL_MS BIGINT NOT NULL DEFAULT 86400000,
    UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_MODEL_CACHE_PROVIDER ON PROVIDER_MODEL_CACHE(PROVIDER_ID);
