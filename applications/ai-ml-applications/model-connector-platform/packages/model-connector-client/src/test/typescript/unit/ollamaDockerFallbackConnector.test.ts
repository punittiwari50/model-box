import test, { describe, it } from "node:test";
import assert from "node:assert/strict";
import {
  OllamaDockerFallbackConnector,
  type IOllamaDockerFallbackConnector,
} from "@/adapters/OllamaDockerFallbackConnector.js";
import { OLLAMA_DOCKER_CANDIDATE_URLS, ModelCatalogDefaults } from "@/domain/constants/index.js";

describe("OllamaDockerFallbackConnector Tests (Docker Container & Default Fallback)", () => {
  it("initializes with candidate Docker URLs covering container and loopback ports", () => {
    const connector = new OllamaDockerFallbackConnector();
    assert.ok(connector !== null);
    assert.ok(OLLAMA_DOCKER_CANDIDATE_URLS.includes("http://localhost:11435"));
    assert.ok(OLLAMA_DOCKER_CANDIDATE_URLS.includes("http://host.docker.internal:11435"));
    assert.ok(OLLAMA_DOCKER_CANDIDATE_URLS.includes("http://127.0.0.1:11435"));
    assert.ok(OLLAMA_DOCKER_CANDIDATE_URLS.includes("http://ollama:11434"));
  });

  it("determines fallback eligibility correctly avoiding non-existent test models", () => {
    const connector = new OllamaDockerFallbackConnector();
    assert.strictEqual(
      connector.canAttemptFallback({ prompt: "Hello", model: "gemini-3.8-flash" }),
      true,
    );
    assert.strictEqual(
      connector.canAttemptFallback({ prompt: "Hello", model: "non-existent-cli-model" }),
      false,
      "Strict negative tests must not trigger fallback mock",
    );
  });

  it("selects exact or prefix model match from container tags", () => {
    const connector = new OllamaDockerFallbackConnector();
    // Use selectBestModel via prototype inspection
    const selectBest = (connector as any).selectBestModel.bind(connector);
    const tags = ["llama3.2:latest", "lfm3-omni:latest", "deepseek-r1:8b"];

    assert.strictEqual(selectBest(tags, "llama3.2"), "llama3.2:latest");
    assert.strictEqual(selectBest(tags, "lfm3-omni"), "lfm3-omni:latest");
    assert.strictEqual(selectBest(tags, "deepseek-r1"), "deepseek-r1:8b");
    assert.strictEqual(selectBest(tags, "gemini-3.8-flash"), "llama3.2:latest", "Falls back to default container model");
  });

  it("builds fallback response with structured envelope and fallback indicators", () => {
    const connector = new OllamaDockerFallbackConnector();
    const buildResponse = (connector as any).buildFallbackResponse.bind(connector);

    const mockData = {
      response: "Fallback text generated by Ollama Docker container",
      prompt_eval_count: 8,
      eval_count: 14,
    };

    const request = {
      prompt: "Execute fallback",
      model: "gemini-3.8-flash",
      requestId: "req-fallback-1",
      taskId: "task-fb-1",
      userId: "user-fb-1",
      userEmail: "fb@company.com",
    };

    const response = buildResponse(
      mockData,
      "llama3.2",
      "http://localhost:11435",
      request,
      Date.now() - 50,
      "corr-fb-1",
    );

    assert.strictEqual(response.content, "Fallback text generated by Ollama Docker container");
    assert.strictEqual(response.model, "llama3.2");
    assert.strictEqual(response.fallbackOccurred, true);
    assert.strictEqual(response.fallbackProvider, "ollama");
    assert.strictEqual(response.requestId, "req-fallback-1");
    assert.strictEqual(response.taskId, "task-fb-1");
    assert.strictEqual(response.userId, "user-fb-1");
    assert.strictEqual(response.userEmail, "fb@company.com");
    assert.ok(response.envelope !== undefined);
    assert.strictEqual(response.envelope?.fallbackOccurred, true);
    assert.strictEqual(response.envelope?.fallbackProvider, "ollama");
  });
});

