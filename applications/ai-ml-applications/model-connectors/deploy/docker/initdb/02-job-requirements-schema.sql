-- ==============================================================================
-- MODELBOX JOB REQUIREMENTS DDL
-- Stores structured job requirements, extracted tech stacks, and LinkedIn URLs
-- ==============================================================================

CREATE TABLE IF NOT EXISTS MB_JOB_REQUIREMENTS (
    JOB_ID VARCHAR(128) PRIMARY KEY,
    JOB_TITLE VARCHAR(255) NOT NULL,
    COMPANY_NAME VARCHAR(255) NOT NULL,
    LOCATION VARCHAR(255),
    LINKEDIN_URL TEXT NOT NULL,
    WORKPLACE_TYPE VARCHAR(64) DEFAULT 'Remote',
    EXPERIENCE_LEVEL VARCHAR(64) DEFAULT 'Mid-Senior level',
    EMPLOYMENT_TYPE VARCHAR(64) DEFAULT 'Full-time',
    RAW_DESCRIPTION TEXT NOT NULL,
    STRUCTURED_REQUIREMENTS_MD TEXT NOT NULL,
    TECH_STACK_JSON JSONB NOT NULL DEFAULT '[]'::jsonb,
    KEY_RESPONSIBILITIES_JSON JSONB NOT NULL DEFAULT '[]'::jsonb,
    QUALIFICATIONS_JSON JSONB NOT NULL DEFAULT '[]'::jsonb,
    SALARY_INSIGHTS VARCHAR(128) DEFAULT 'Not Specified',
    MARKDOWN_FILE_PATH TEXT,
    OFFICIAL_APPLY_URL TEXT,
    FIRST_LISTED_AT TIMESTAMPTZ,
    EXTRACTED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    METADATA_JSON JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS IDX_MB_JOB_REQ_TITLE ON MB_JOB_REQUIREMENTS (JOB_TITLE);
CREATE INDEX IF NOT EXISTS IDX_MB_JOB_REQ_COMPANY ON MB_JOB_REQUIREMENTS (COMPANY_NAME);
CREATE INDEX IF NOT EXISTS IDX_MB_JOB_REQ_EXTRACTED ON MB_JOB_REQUIREMENTS (EXTRACTED_AT);
CREATE INDEX IF NOT EXISTS IDX_MB_JOB_REQ_FIRST_LISTED ON MB_JOB_REQUIREMENTS (FIRST_LISTED_AT DESC NULLS LAST, EXTRACTED_AT DESC);
