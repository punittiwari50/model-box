-- ============================================================================
-- ModelBox Architecture: Unified Master DDL Schema
-- Location: config/scripts/sql/schema-ddl.sql
-- Conforms to: STD-COD-001, STD-COD-002, STD-COD-005, STD-COD-007, Invariant #13
--
-- Concurrency & Performance Engine:
--   - WAL (Write-Ahead Logging) for non-blocking concurrent readers & writers
--   - Busy timeout to prevent SQLITE_BUSY under heavy concurrent load
--   - Foreign key cascading enabled for referential integrity
--   - Optimistic concurrency control (VERSION column) on mutable entities
--   - B-Tree covering indexes for sub-millisecond lookups and sorting
--   - Canonical created_timestamp and update_timestamp across all tables
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Database Engine Pragmas (Concurrency, Performance & Integrity)
-- ----------------------------------------------------------------------------
PRAGMA foreign_keys = ON;
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;
PRAGMA busy_timeout = 10000;
PRAGMA cache_size = -64000;
PRAGMA temp_store = MEMORY;

-- ----------------------------------------------------------------------------
-- 2. Core Entity: CONVERSATIONS (Parent Table)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CONVERSATIONS (
  ID TEXT PRIMARY KEY,
  SESSION_ID TEXT,
  TITLE TEXT NOT NULL,
  MODEL TEXT NOT NULL,
  SYSTEM_INSTRUCTION TEXT,
  TAGS TEXT NOT NULL DEFAULT '[]',
  METADATA TEXT NOT NULL DEFAULT '{}',
  VERSION INTEGER NOT NULL DEFAULT 1,
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 3. Dependent Entity: MESSAGES (Child Table -> CONVERSATIONS)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS MESSAGES (
  ID TEXT PRIMARY KEY,
  CONVERSATION_ID TEXT NOT NULL,
  ROLE TEXT NOT NULL,
  CONTENT TEXT NOT NULL,
  MODEL TEXT,
  PROMPT_TOKENS INTEGER,
  COMPLETION_TOKENS INTEGER,
  TOTAL_TOKENS INTEGER,
  LATENCY_MS REAL,
  CLI_EXIT_CODE INTEGER,
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(CONVERSATION_ID) REFERENCES CONVERSATIONS(ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 4. Dependent Entity: CONTEXT_ITEMS (Child Table -> CONVERSATIONS)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CONTEXT_ITEMS (
  ID TEXT PRIMARY KEY,
  CONVERSATION_ID TEXT NOT NULL,
  CONTEXT_TYPE TEXT NOT NULL,
  TITLE TEXT NOT NULL,
  CONTENT TEXT NOT NULL,
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(CONVERSATION_ID) REFERENCES CONVERSATIONS(ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 5. Governance Entity: AUDIT_LOGS (Security & Compliance Trail)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
  ID TEXT PRIMARY KEY,
  CONVERSATION_ID TEXT,
  ACTION TEXT NOT NULL,
  CLIENT_IP TEXT,
  MODEL_USED TEXT,
  PROMPT_TOKENS INTEGER,
  COMPLETION_TOKENS INTEGER,
  LATENCY_MS REAL,
  STATUS TEXT NOT NULL,
  ERROR_MESSAGE TEXT,
  DETAILS TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 6. Authentication Entity: MODEL_AUTH (Multi-Model Dedicated Accounts & Tokens)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS MODEL_AUTH (
  ID TEXT PRIMARY KEY,
  MODEL TEXT NOT NULL,
  AUTH_TYPE TEXT NOT NULL,
  ACCOUNT_EMAIL TEXT,
  ACCOUNT_NAME TEXT,
  ACCESS_TOKEN TEXT NOT NULL,
  REFRESH_TOKEN TEXT,
  EXPIRES_AT TEXT,
  METADATA TEXT NOT NULL DEFAULT '{}',
  STATUS TEXT NOT NULL DEFAULT 'AUTHENTICATED',
  IS_ACTIVE INTEGER NOT NULL DEFAULT 1,
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 7. Analytics Entity: ORGANIZATION_USAGE_METRICS (Token & Cost Tracking)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ORGANIZATION_USAGE_METRICS (
  ID TEXT PRIMARY KEY,
  ORG_ID TEXT NOT NULL DEFAULT 'default-org',
  PROJECT_ID TEXT NOT NULL DEFAULT 'default-project',
  MODEL TEXT NOT NULL,
  EXECUTION_MODE TEXT NOT NULL,
  REQUEST_COUNT INTEGER NOT NULL DEFAULT 1,
  PROMPT_TOKENS INTEGER NOT NULL DEFAULT 0,
  COMPLETION_TOKENS INTEGER NOT NULL DEFAULT 0,
  TOTAL_TOKENS INTEGER NOT NULL DEFAULT 0,
  ESTIMATED_COST_USD REAL NOT NULL DEFAULT 0.0,
  EXECUTION_TIME_MS REAL NOT NULL DEFAULT 0.0,
  CONCURRENCY_LEVEL INTEGER NOT NULL DEFAULT 1,
  STATUS TEXT NOT NULL DEFAULT 'SUCCESS',
  TRACE_ID TEXT,
  CORRELATION_ID TEXT,
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 8. Prompt Repository: JOB_SEARCH_PROMPTS (Dynamic DB Prompts & Instructions)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS JOB_SEARCH_PROMPTS (
  ID TEXT PRIMARY KEY,
  PROMPT_KEY TEXT NOT NULL,
  PROMPT_TYPE TEXT NOT NULL,
  CONTENT TEXT NOT NULL,
  DESCRIPTION TEXT,
  METADATA TEXT NOT NULL DEFAULT '{}',
  VERSION INTEGER NOT NULL DEFAULT 1,
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 9. Concurrency & Diagnostics Entity: PERF_TEST (Connection Pool Benchmark)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PERF_TEST (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  VAL TEXT,
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 10. Autonomous Agent Entity: AGENT_EXECUTIONS (Gemini CLI / MCP Agent Runs)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS AGENT_EXECUTIONS (
  ID TEXT PRIMARY KEY,
  AGENT_NAME TEXT NOT NULL,
  PROJECT TEXT NOT NULL DEFAULT 'default',
  TASK TEXT NOT NULL,
  MODEL TEXT NOT NULL,
  APPROVAL_MODE TEXT NOT NULL DEFAULT 'default',
  SANDBOX INTEGER NOT NULL DEFAULT 1,
  STATUS TEXT NOT NULL DEFAULT 'RUNNING',
  SKILLS TEXT NOT NULL DEFAULT '[]',
  RESULT TEXT,
  ERROR_MESSAGE TEXT,
  PROMPT_TOKENS INTEGER,
  COMPLETION_TOKENS INTEGER,
  TOTAL_TOKENS INTEGER,
  LATENCY_MS REAL,
  SUBSCRIPTION_TIER TEXT NOT NULL DEFAULT 'freeware',
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 11. Autonomous Agent Dependent Entity: AGENT_STEPS (Child Table -> AGENT_EXECUTIONS)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS AGENT_STEPS (
  ID TEXT PRIMARY KEY,
  AGENT_ID TEXT NOT NULL,
  STEP_NUMBER INTEGER NOT NULL,
  STEP_TYPE TEXT NOT NULL,
  CONTENT TEXT NOT NULL,
  TOOL_NAME TEXT,
  STATUS TEXT NOT NULL DEFAULT 'SUCCESS',
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(AGENT_ID) REFERENCES AGENT_EXECUTIONS(ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 12. Hyperparameters Entity: MODEL_HYPERPARAMETERS (DB Overrides & Tunings)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS MODEL_HYPERPARAMETERS (
  ID TEXT PRIMARY KEY,
  MODEL TEXT NOT NULL,
  TIER TEXT,
  TEMPERATURE REAL,
  TOP_P REAL,
  MAX_OUTPUT_TOKENS INTEGER,
  TIMEOUT_MS INTEGER,
  ALLOW_MOCK_FALLBACK INTEGER,
  FALLBACK_THRESHOLD_PERCENTAGE INTEGER,
  METADATA TEXT NOT NULL DEFAULT '{}',
  CREATED_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIMESTAMP TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- High-Performance Concurrent Indexes (Sequential Order)
-- ============================================================================

-- CONVERSATIONS Indexes
CREATE INDEX IF NOT EXISTS IDX_CONVERSATIONS_SESSION ON CONVERSATIONS(SESSION_ID);
CREATE INDEX IF NOT EXISTS IDX_CONVERSATIONS_UPDATED ON CONVERSATIONS(UPDATE_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_CONVERSATIONS_MODEL_UPDATED ON CONVERSATIONS(MODEL, UPDATE_TIMESTAMP DESC);

-- MESSAGES Indexes
CREATE INDEX IF NOT EXISTS IDX_MESSAGES_CONV ON MESSAGES(CONVERSATION_ID, CREATED_TIMESTAMP ASC);
CREATE INDEX IF NOT EXISTS IDX_MESSAGES_MODEL ON MESSAGES(MODEL, CREATED_TIMESTAMP ASC);

-- CONTEXT_ITEMS Indexes
CREATE INDEX IF NOT EXISTS IDX_CONTEXT_CONV ON CONTEXT_ITEMS(CONVERSATION_ID, CREATED_TIMESTAMP ASC);
CREATE INDEX IF NOT EXISTS IDX_CONTEXT_TYPE ON CONTEXT_ITEMS(CONVERSATION_ID, CONTEXT_TYPE);

-- AUDIT_LOGS Indexes
CREATE INDEX IF NOT EXISTS IDX_AUDIT_TIMESTAMP ON AUDIT_LOGS(CREATED_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_CONV ON AUDIT_LOGS(CONVERSATION_ID, CREATED_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_ACTION ON AUDIT_LOGS(ACTION, CREATED_TIMESTAMP DESC);

-- MODEL_AUTH Indexes
CREATE INDEX IF NOT EXISTS IDX_MODEL_AUTH_MODEL ON MODEL_AUTH(MODEL);
CREATE INDEX IF NOT EXISTS IDX_MODEL_AUTH_STATUS ON MODEL_AUTH(STATUS);
CREATE INDEX IF NOT EXISTS IDX_MODEL_AUTH_ACTIVE ON MODEL_AUTH(IS_ACTIVE);

-- ORGANIZATION_USAGE_METRICS Indexes
CREATE INDEX IF NOT EXISTS IDX_ORG_METRICS_ORG_PROJ ON ORGANIZATION_USAGE_METRICS(ORG_ID, PROJECT_ID);
CREATE INDEX IF NOT EXISTS IDX_ORG_METRICS_MODEL ON ORGANIZATION_USAGE_METRICS(MODEL);
CREATE INDEX IF NOT EXISTS IDX_ORG_METRICS_CREATED ON ORGANIZATION_USAGE_METRICS(CREATED_TIMESTAMP DESC);

-- JOB_SEARCH_PROMPTS Indexes
CREATE UNIQUE INDEX IF NOT EXISTS IDX_JOB_PROMPTS_KEY ON JOB_SEARCH_PROMPTS(PROMPT_KEY);
CREATE INDEX IF NOT EXISTS IDX_JOB_PROMPTS_TYPE ON JOB_SEARCH_PROMPTS(PROMPT_TYPE);

-- AGENT_EXECUTIONS Indexes
CREATE INDEX IF NOT EXISTS IDX_AGENT_EXECUTIONS_STATUS ON AGENT_EXECUTIONS(STATUS);
CREATE INDEX IF NOT EXISTS IDX_AGENT_EXECUTIONS_UPDATED ON AGENT_EXECUTIONS(UPDATE_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_AGENT_EXECUTIONS_MODEL ON AGENT_EXECUTIONS(MODEL, UPDATE_TIMESTAMP DESC);
CREATE INDEX IF NOT EXISTS IDX_AGENT_EXECUTIONS_PROJECT ON AGENT_EXECUTIONS(PROJECT, UPDATE_TIMESTAMP DESC);

-- AGENT_STEPS Indexes
CREATE INDEX IF NOT EXISTS IDX_AGENT_STEPS_AGENT ON AGENT_STEPS(AGENT_ID, STEP_NUMBER ASC);

-- MODEL_HYPERPARAMETERS Indexes
CREATE UNIQUE INDEX IF NOT EXISTS IDX_MODEL_HYPERPARAMS_MODEL_TIER ON MODEL_HYPERPARAMETERS(MODEL, TIER);
